// Writes src/data/projectIndex.js: every project with only the fields the
// home page uses (titles, hooks, links, covers, numbers). The full stories in
// projects.js are for the project pages, which load on their own; keeping
// them out of the home page halves its first load.
//
// Run after changing projects.js:   node scripts/make-project-index.mjs
// (src/data/projectIndex.test.mjs fails if the index is out of date.)
import { writeFile } from 'node:fs/promises';
import { ACCENTS, EXPERIMENTS, PROJECTS } from '../src/data/projects.js';
import { indexOf } from '../src/data/projectIndexFields.js';

const body = `// Generated by scripts/make-project-index.mjs from projects.js. Do not edit.
// The home page's slice of every project; see the script for why.
export const ACCENTS = ${JSON.stringify(ACCENTS)};
export const EXPERIMENTS = ${JSON.stringify(EXPERIMENTS)};
export const PROJECT_INDEX = ${JSON.stringify(PROJECTS.map(indexOf))};

// Same rules as projects.js: \`hidden\` keeps a page working but out of lists.
const listed = (p) => !p.hidden;
export const LISTED_PROJECTS = PROJECT_INDEX.filter(listed);
export const OPEN_SOURCE_PROJECTS = PROJECT_INDEX.filter((p) => p.spotlightGroup === "open-source" && listed(p));
export const getProject = (slug) => PROJECT_INDEX.find((p) => p.slug === slug);
`;
await writeFile('src/data/projectIndex.js', body);
console.log(`wrote src/data/projectIndex.js: ${PROJECTS.length} projects, ${body.length} bytes`);
